export function applyPreset(name) {
  const preset = CONFIG.presets[name] || CONFIG.presets.Balanced;
  CONFIG.tires.baseMu = 1.18 * preset.grip;
  CONFIG.car.counterSteerAssist = 0.18 * preset.steeringAssist;
  CONFIG.drift.assistStrength = 0.7 * preset.driftAssist;
  CONFIG.brakes.abs = preset.abs;
  return preset;
}
